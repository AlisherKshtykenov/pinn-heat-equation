import numpy as np

BETA = 1e-5  # коэффициент температуропроводности
T = 12_000.0  # конечное время
U_LEFT = 1.0  # условие Дирихле: u(0, t) = 1
UX_RIGHT = 2.0  # условие Неймана: u_x(1, t) = 2
REPORT_TIMES = (0.0, 3000.0, 6000.0, 12000.0)  # контрольные моменты времени


def initial_condition(x):
    """Начальный профиль u(x, 0) = 2x + sin(2 pi x) + 1."""
    return 2.0 * x + np.sin(2.0 * np.pi * x) + 1.0


def steady_state(x):
    """Стационарное решение u_s(x) = 2x + 1."""
    return 2.0 * x + 1.0
